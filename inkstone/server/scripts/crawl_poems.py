def import_poems():
    """Import curated poems into the database."""
    existing = query('SELECT COUNT(*) as cnt FROM poems')
    if existing[0]['cnt'] > 0:
        print(f'Poems already seeded ({existing[0]["cnt"]} poems).')
        return

    count = 0
    for category, poems in POEMS.items():
        for title, author, dynasty, content in poems:
            execute(
                'INSERT INTO poems (title, author, dynasty, content, category, source) VALUES (%s, %s, %s, %s, %s, %s)',
                (title, author, dynasty, content, category, '古典诗词精选')
            )
            count += 1

    print(f'Imported {count} poems across {len(POEMS)} categories.')


if __name__ == '__main__':
    print('Importing poem library...')
    import_poems()
    print('Done!')
