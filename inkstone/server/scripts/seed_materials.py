def import_materials():
    """Import curated materials into the database."""
    existing = query('SELECT COUNT(*) as cnt FROM materials')
    if existing[0]['cnt'] > 0:
        print(f'Materials already seeded ({existing[0]["cnt"]} items).')
        return

    count = 0
    for category, items in MATERIALS.items():
        for title, content, tags in items:
            execute(
                'INSERT INTO materials (title, content, category, tags, source) VALUES (%s, %s, %s, %s, %s)',
                (title, content, category, tags, '写作素材精选')
            )
            count += 1

    print(f'Imported {count} materials across {len(MATERIALS)} categories.')


if __name__ == '__main__':
    print('Importing materials library...')
    import_materials()
    print('Done!')
