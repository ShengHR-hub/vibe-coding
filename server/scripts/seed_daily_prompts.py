def import_daily_prompts():
    """Import daily prompts into the database."""
    existing = query('SELECT COUNT(*) as cnt FROM daily_prompts')
    if existing[0]['cnt'] > 0:
        print(f'Daily prompts already seeded ({existing[0]["cnt"]} items).')
        return

    today = date.today()
    count = 0
    for i, (title, desc, ptype, wmin, wmax, diff, tags) in enumerate(DAILY_PROMPTS):
        # Assign active_date in rotation so each day gets one prompt
        active = today - timedelta(days=len(DAILY_PROMPTS) - 1 - i)
        execute(
            'INSERT INTO daily_prompts (title, description, type, word_min, word_max, difficulty, tags, active_date) VALUES (%s, %s, %s, %s, %s, %s, %s, %s)',
            (title, desc, ptype, wmin, wmax, diff, tags, active)
        )
        count += 1

    print(f'Imported {count} daily prompts.')


if __name__ == '__main__':
    print('Importing daily prompts...')
    import_daily_prompts()
    print('Done!')
